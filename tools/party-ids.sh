#!/usr/bin/env bash
# Resolve the party IDs of the localnet and write them to an env file consumed by docker compose.
# Party IDs are generated on first start and change whenever the postgres volume is recreated,
# so they cannot be hardcoded.
#
#   APP_USER_PARTY_ID, APP_PROVIDER_PARTY_ID, SV_PARTY_ID
#       validator party of each participant (primary party of ledger-api-user)
#   UTILITY_OPERATOR_PARTY_ID
#       Utilities registry operator, a dedicated party on the sv participant. Allocated here on first
#       run; ledger-api-user on sv gets CanActAs for it (used by the examples, PQS and hosted-backend).
#
# Usage: tools/party-ids.sh <output-env-file>
set -euo pipefail

out="${1:?usage: $0 <output-env-file>}"

# Static HS256 JWT (secret "unsafe") for sub=ledger-api-user, aud=https://canton.network.global
token="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJsZWRnZXItYXBpLXVzZXIiLCJhdWQiOiJodHRwczovL2NhbnRvbi5uZXR3b3JrLmdsb2JhbCJ9.G9aLv-IF5X0WmIkbR10f48i-7it5LlgwpJEZ4Ce2Y-E"
operator_hint="utility-operator"
sv_port=4975

api() {
  local method="$1" port="$2" path="$3" body="${4:-}"
  curl -sf -m 10 -X "$method" -H "Authorization: Bearer $token" -H "Content-Type: application/json" \
    ${body:+--data "$body"} "http://127.0.0.1:${port}${path}"
}

# Validator party: primary party of ledger-api-user (waits until the validator has onboarded it)
validator_party() {
  local port="$1" party=""
  for _ in $(seq 1 60); do
    party=$(api GET "$port" /v2/users/ledger-api-user 2>/dev/null \
      | grep -oE '"primaryParty":"[^"]+"' | sed -E 's/.*:"([^"]+)"/\1/') || true
    [ -n "$party" ] && { echo "$party"; return 0; }
    sleep 5
  done
  echo "party-ids: could not resolve validator party on JSON API port ${port}" >&2
  return 1
}

# Utility operator party on sv: find it among the local parties, allocate it if missing.
# Runs inside $(...), where bash ignores set -e, so every failure is checked explicitly.
utility_operator() {
  local party
  party=$(api GET "$sv_port" /v2/parties | grep -oE "\"party\":\"${operator_hint}::[^\"]+\"" | head -1 \
    | sed -E 's/.*:"([^"]+)"/\1/') || true
  if [ -z "$party" ]; then
    party=$(api POST "$sv_port" /v2/parties "{\"partyIdHint\":\"${operator_hint}\",\"identityProviderId\":\"\"}" \
      | grep -oE '"party":"[^"]+"' | head -1 | sed -E 's/.*:"([^"]+)"/\1/') || true
    if [ -z "$party" ]; then
      echo "party-ids: could not allocate party ${operator_hint} on JSON API port ${sv_port}" >&2
      return 1
    fi
    echo "party-ids: allocated ${party}" >&2
  fi
  # Idempotent: granting an existing right is a no-op
  if ! api POST "$sv_port" /v2/users/ledger-api-user/rights \
    "{\"userId\":\"ledger-api-user\",\"identityProviderId\":\"\",\"rights\":[{\"kind\":{\"CanActAs\":{\"value\":{\"party\":\"${party}\"}}}}]}" >/dev/null; then
    echo "party-ids: could not grant ledger-api-user CanActAs ${party}" >&2
    return 1
  fi
  echo "$party"
}

app_user=$(validator_party 2975)
app_provider=$(validator_party 3975)
sv=$(validator_party "$sv_port")
operator=$(utility_operator)

{
  echo "# Generated by tools/party-ids.sh — do not edit"
  echo "APP_USER_PARTY_ID=${app_user}"
  echo "APP_PROVIDER_PARTY_ID=${app_provider}"
  echo "SV_PARTY_ID=${sv}"
  echo "UTILITY_OPERATOR_PARTY_ID=${operator}"
} > "$out"
cat "$out"
